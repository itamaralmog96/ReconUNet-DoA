    @staticmethod
    def _rmspe(pred: np.ndarray, target: np.ndarray) -> float:
        """Root-Mean-Square Periodic Error (degrees, order-invariant)."""
        if len(pred) == 0 or len(target) == 0:
            return float("inf")

        from itertools import permutations

        rmspe_vals = []
        for p in permutations(pred, len(target)):
            p_arr, t_arr = np.asarray(p), np.asarray(target)
            err = ((np.abs(p_arr - t_arr) * np.pi / 180))
            err = err * 180 / np.pi
            rmspe_vals.append((1 / np.sqrt(len(p_arr))) * np.linalg.norm(err))
        return float(np.min(rmspe_vals)) if rmspe_vals else float("inf")

    def _detect_array_cfg_from_dataset(self) -> dict[str, Any]:
        """Extract comprehensive array configuration from dataset metadata."""

        import h5py, json as _json

        # Default values
        array_config = {
            "array_type": "linear",
            "num_elements": 8,
            "carrier_freq": 2.45e9,
            "element_spacing": 0.5,
            "enable_gain_phase_errors": False,
            "enable_mutual_coupling": False,
            "position_error_std": 0.0,
            "radius": 0.5,
            "gain_error_range": (0.975, 1.025),
            "phase_error_range_deg": (-5.0, 5.0),
            "coupling_strength": 0.3,
            "coupling_phase_deg": -100.0,
            "coupling_variation": 0.9,
        }

        try:
            with h5py.File(self.cfg.dataset_path, "r") as _f:
                # First try to get from global config attribute (simple case)
                if "config" in _f.attrs:
                    cfg_json = _f.attrs["config"]
                    if isinstance(cfg_json, bytes):
                        cfg_json = cfg_json.decode()
                    cfg_dict = _json.loads(cfg_json)
                    array_config["array_type"] = cfg_dict.get("array_type", array_config["array_type"])
                    array_config["num_elements"] = int(cfg_dict.get("num_elements", array_config["num_elements"]))
                    array_config["carrier_freq"] = float(cfg_dict.get("carrier_freq", array_config["carrier_freq"]))
                    array_config["sampling_freq"] = float(cfg_dict.get("sampling_freq", 1e6))
                
                # Try to get detailed array model configuration from first sample with array imperfections = False
                # This gives us the nominal array configuration used during generation
                if "array_models" in _f and len(_f["array_models/array_type"]) > 0:
                    # Find first sample with array_imperfections = False to get nominal config
                    nominal_idx = 0
                    if "array_imperfections" in _f["array_models"]:
                        imperfections = _f["array_models/array_imperfections"][:]
                        nominal_indices = np.where(imperfections == False)[0]
                        if len(nominal_indices) > 0:
                            nominal_idx = nominal_indices[0]
                    
                    # Extract detailed array configuration from dataset
                    array_config["array_type"] = _f["array_models/array_type"][nominal_idx].decode('utf-8')
                    array_config["num_elements"] = int(_f["array_models/num_elements"][nominal_idx])
                    array_config["carrier_freq"] = float(_f["array_models/carrier_freq"][nominal_idx])
                    
                    # Optional fields with fallbacks
                    if "element_spacing" in _f["array_models"]:
                        array_config["element_spacing"] = float(_f["array_models/element_spacing"][nominal_idx])
                    if "radius" in _f["array_models"]:
                        array_config["radius"] = float(_f["array_models/radius"][nominal_idx])
                    
                    # For nominal array model, we want imperfections disabled
                    array_config["enable_gain_phase_errors"] = False
                    array_config["enable_mutual_coupling"] = False
                    array_config["position_error_std"] = 0.0
                    
                    print(f"[INFO] Extracted array config from dataset: {array_config['array_type']} array with {array_config['num_elements']} elements")
                else:
                    # Fallback to signal shape analysis
                    if "received_signals" in _f and "shapes" in _f["received_signals"]:
                        array_config["num_elements"] = int(_f["received_signals/shapes"][0][0])
                        print(f"[INFO] Inferred num_elements={array_config['num_elements']} from received signal shape")

        except Exception as e:
            print(f"[WARN] Could not read detailed dataset metadata – {e}. Using defaults.")

        # Scan-angle range based on array geometry
        if array_config["array_type"] == "linear":
            scan_angles = np.arange(0, 181, 1)
        else:
            scan_angles = np.arange(0, 360, 1)

        array_config["scan_angles"] = scan_angles
        return array_config

    def _create_nominal_array_model(self) -> ArrayModel:
        """Create nominal array model from dataset configuration."""
        array_cfg = ArrayConfig(
            array_type=self._array_cfg_dict["array_type"],
            num_elements=self._array_cfg_dict["num_elements"],
            carrier_freq=self._array_cfg_dict["carrier_freq"],
            element_spacing=self._array_cfg_dict["element_spacing"],
            enable_gain_phase_errors=False,  # Always false for nominal model
            enable_mutual_coupling=False,    # Always false for nominal model
            position_error_std=0.0,          # Always 0 for nominal model
        )
        # Use a fixed seed for reproducible nominal array model
        return ArrayModel(array_cfg, seed=42)

    def _init_classic_algs(self, array_model: ArrayModel, scan_angles: np.ndarray):
        algs = {}
        for name in self.cfg.classic_algorithms:
            n = name.lower()
            if n == "beamformer":
                algs[name] = Beamformer(array_model=array_model, scan_angles_deg=scan_angles)
            elif n == "music":
                algs[name] = MUSIC(array_model=array_model, scan_angles_deg=scan_angles)
            elif n == "mvdr":
                algs[name] = MVDR(array_model=array_model, scan_angles_deg=scan_angles)
            elif n == "rootmusic":
                algs[name] = RootMUSIC(array_model=array_model, scan_angles_deg=scan_angles)
        return algs

