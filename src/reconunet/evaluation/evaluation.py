    # Public orchestration ----------------------------------------------
    # ------------------------------------------------------------------
    def run(self):
        """Run all requested evaluations and save a JSON summary."""
        t_start = time.time()

        # ---------------- Classic --------------------------------------
        self._evaluate_classic()

        # ---------------- Deep & augmented -----------------------------
        self._evaluate_deep(self.cfg.deep_models, group_tag="deep")
        self._evaluate_deep(self.cfg.augmented_models, group_tag="augmented")

        # ---------------- Generate plots -------------------------------
        if self.cfg.create_plots:
            print("\n=== Generating plots ===")
            self._plot_rmspe_vs_snr()

        # ---------------- Persist summary ------------------------------
        summary = {
            "config": asdict(self.cfg),
            "results": self._results,
            "timings_ms": self._timings,
            "timestamp": _timestamp(),
            "runtime_sec": round(time.time() - t_start, 3),
        }

        save_path = self._results_dir / f"tri4net_evaluation_{_timestamp()}.json"
        
        # Custom JSON serializer to handle numpy types
        def json_serializer(obj):
            if isinstance(obj, np.integer):
                return int(obj)
            elif isinstance(obj, np.floating):
                return float(obj)
            elif isinstance(obj, np.ndarray):
                return obj.tolist()
            return float(obj)  # fallback
        
        with open(save_path, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2, sort_keys=False, default=json_serializer)

        print("\n===================================================")
        print("Evaluation finished.")
        print(f"Summary JSON saved to: {save_path}")
        print("===================================================\n")

        return summary 

