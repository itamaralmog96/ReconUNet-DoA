"""Unified evaluation utility for ReconUNet.

This script provides a *single* entry-point that can benchmark:

1. Classic model-based DOA algorithms (Beamformer, MUSIC, MVDR, RootMUSIC …)
2. Augmented hybrids (e.g. SubspaceNet-based, Deep-Root-MUSIC, etc.)
3. Pure deep-learning approaches (CNN-DoA, ViT, Grid-Net …)

The implementation intentionally keeps each evaluation step concise while
re-using the specialised evaluators that already live inside the code-base.
It mirrors SubspaceNet's original ``evaluation.py`` design but is adapted to
ReconUNet naming conventions and folder layout.

Example
-------
>>> from reconunet.evaluation.evaluation import EvaluationConfig, DOAEvaluator
>>> cfg = EvaluationConfig(
...     dataset_path="data/datasets/linear/ula_dataset/ula_dataset.h5",
...     classic_algorithms=["beamformer", "music", "mvdr", "rootmusic"],
...     deep_models=["subspace_net", "cnn_doa"],
... )
>>> DOAEvaluator(cfg).run()
"""

