    def _evaluate_deep(self, model_keys: List[str], group_tag: str):
        # Respect category toggle
        if (group_tag == "deep" and not self.cfg.run_deep) or (
            group_tag == "augmented" and not self.cfg.run_augmented
        ):
            return

        if not model_keys:
            return
        import copy
        from collections import defaultdict

        DEVICE = torch.device(self.cfg.device)
        rmspe_criterion = RMSPELoss().to(DEVICE)

        deep_results = {}
        deep_timing = {}

        for model_key in model_keys:
            print(f"\n=== Evaluating deep model: {model_key} ===")

            # ------------------------------------------------------------------
            # Build *processed* dataset exactly like the training pipeline
            # ------------------------------------------------------------------
            proc_dataset, meta = _engine._build_dataset(  # type: ignore[attr-defined]
                dataset_path=self.cfg.dataset_path,
                model_key=model_key,
                tau=self.cfg.tau,
            )

            loader = DataLoader(
                proc_dataset,
                batch_size=self.cfg.batch_size,
                shuffle=False,
                num_workers=self.cfg.num_workers,
            )

            N, T, M_meta = meta  # M_meta is max M present (training returns meta)

            # SubspaceNet-family (+variants) require evaluation **per-M**
            variable_models = {
                "subspace_net",
                "subspace_net_esprit",
                "deep_root_music",
                "deep_augmented_music",
            }

            # ------------------------------------------------------------------
            # Instantiate models ------------------------------------------------
            # ------------------------------------------------------------------
            def _instantiate(m_val: int):
                mdl = _engine._instantiate_model(  # type: ignore[attr-defined]
                    model_key=model_key,
                    N=N,
                    T=T,
                    M=m_val,
                    tau=self.cfg.tau,
                ).to(DEVICE)
                mdl._model_key = model_key  # type: ignore[attr-defined]
                return mdl

            # ------------------------------------------------------------------
            # Map M -> loader subset (if variable); else single loader ----------
            # ------------------------------------------------------------------
            if model_key in variable_models:
                # Build indices per-M (like training.engine)
                from collections import defaultdict as _dd

                groups_idx = _dd(list)
                for idx in range(len(proc_dataset.base_ds)):
                    m_val = len(proc_dataset.base_ds[idx]["labels"]["doas"])
                    groups_idx[m_val].append(idx)

                model_rmse: Dict[int, float] = {}
                model_time: Dict[int, float] = {}

                for m_val, indices in groups_idx.items():
                    subset = torch.utils.data.Subset(proc_dataset, indices)
                    sub_loader = DataLoader(
                        subset,
                        batch_size=self.cfg.batch_size,
                        shuffle=False,
                        num_workers=self.cfg.num_workers,
                    )

                    model = _instantiate(m_val)
                    weight_path = self.cfg.model_weight_paths.get(model_key)
                    if weight_path and Path(weight_path).is_file():
                        model.load_state_dict(torch.load(weight_path, map_location=DEVICE))
                        print(f"  ↪ Loaded weights from {weight_path}")

                    model.eval()

                    running_loss, num_items, total_time = 0.0, 0, 0.0
                    with torch.no_grad():
                        for batch in sub_loader:
                            # training.engine helper prepares batch correctly
                            X, target = _engine._prepare_batch(model_key, batch)  # type: ignore[attr-defined]
                            t0 = time.time()
                            output = model(X.to(DEVICE))
                            forward_time = time.time() - t0
                            total_time += forward_time

                            preds = output[0] if isinstance(output, tuple) else output
                            if model_key in {"subspace_net", "subspace_net_esprit", "deep_root_music"}:
                                preds = preds * np.pi / 180.0  # convert to rad

                            loss = rmspe_criterion(preds, target.to(DEVICE))
                            running_loss += loss.item() * X.size(0)
                            num_items += X.size(0)

                    model_rmse[m_val] = running_loss / num_items if num_items else float("inf")
                    model_time[m_val] = (total_time / num_items * 1000.0) if num_items else float("inf")  # ms per sample

                    print(f"  M={m_val}: RMSPE={model_rmse[m_val]:.3f} | {model_time[m_val]:.1f} ms/sample")

                deep_results[model_key] = model_rmse
                deep_timing[model_key] = model_time
            else:
                # ---------- Fixed-M models --------------------------------
                model = _instantiate(M_meta)
                weight_path = self.cfg.model_weight_paths.get(model_key)
                if weight_path and Path(weight_path).is_file():
                    model.load_state_dict(torch.load(weight_path, map_location=DEVICE))
                    print(f"  ↪ Loaded weights from {weight_path}")

                model.eval()
                running_loss, num_items, total_time = 0.0, 0, 0.0
                with torch.no_grad():
                    for batch in loader:
                        X, target = _engine._prepare_batch(model_key, batch)  # type: ignore[attr-defined]
                        t0 = time.time(); preds = model(X.to(DEVICE)); total_time += time.time() - t0
                        preds = preds[0] if isinstance(preds, tuple) else preds
                        loss = rmspe_criterion(preds, target.to(DEVICE))
                        running_loss += loss.item() * X.size(0)
                        num_items += X.size(0)

                deep_results[model_key] = running_loss / num_items if num_items else float("inf")
                deep_timing[model_key] = (total_time / num_items * 1000.0) if num_items else float("inf")
                print(
                    f"  RMSPE={deep_results[model_key]:.3f} | {deep_timing[model_key]:.1f} ms/sample",
                )

        self._results[group_tag] = deep_results
        self._timings[group_tag] = deep_timing

