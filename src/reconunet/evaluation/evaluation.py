    @staticmethod
    def _scenario_definitions() -> list[dict[str, Any]]:
        """Return the standard 12 scenarios used across projects."""
        base = [
            {"name": "1_source_no_multipath", "num_sources": [1, 0], "num_multipath": 0},
            {"name": "2_sources_no_multipath", "num_sources": [1, 1], "num_multipath": 0},
            {"name": "3_sources_no_multipath", "num_sources": [1, 2], "num_multipath": 0},
            {"name": "1_source_1_multipath", "num_sources": [1, 0], "num_multipath": 1},
            {"name": "1_source_2_multipath", "num_sources": [1, 0], "num_multipath": 2},
            {"name": "2_sources_1_multipath", "num_sources": [1, 1], "num_multipath": 1},
        ]
        scenarios = []
        for b in base:
            scenarios.append({**b, "name": f"{b['name']}_perfect_array", "array_imperfections": False})
            scenarios.append({**b, "name": f"{b['name']}_imperfect_array", "array_imperfections": True})
        return scenarios

    def _selected_scenarios(self) -> list[dict[str, Any]]:
        """Return scenario dicts based on *config.scenarios*."""
        # If user did not request scenario filtering → evaluate entire dataset once
        if self.cfg.scenarios is None or len(self.cfg.scenarios) == 0:
            return [{"name": "all"}]  # special marker – no filtering

        all_scen = {s["name"]: s for s in self._scenario_definitions()}
        sel = []
        for name in self.cfg.scenarios:
            if name in all_scen:
                sel.append(all_scen[name])
            else:
                print(f"[WARN] Unknown scenario '{name}' - skipping.")
        # Fallback to full dataset if none matched
        return sel if sel else [{"name": "all"}]

    def _filter_dataset_by_scenario(self, scenario: dict[str, Any]) -> 'DOADataset':  # noqa: F821 – forward ref
        """Return dataset subset matching *scenario* criteria."""
        ds = self._base_dataset
        # 'all' → no filtering
        if scenario.get("name") == "all":
            return ds

        kwargs = {}
        if scenario.get("num_sources") is not None:
            kwargs["num_sources"] = scenario["num_sources"]
        if scenario.get("num_multipath") is not None:
            kwargs["num_multipath"] = scenario["num_multipath"]
        if scenario.get("array_imperfections") is not None:
            kwargs["array_imperfections"] = scenario["array_imperfections"]
        return ds.filter(**kwargs) if kwargs else ds

    def _evaluate_classic(self):
        if not self.cfg.run_classic or not self.cfg.classic_algorithms:
            return

        print("\n=== Evaluating classic algorithms (internal) ===")
        print(f"[INFO] Using optimized evaluation with cached array model and algorithms")

        # OPTIMIZATION: Use cached array model and algorithms instead of recreating
        alg_instances = self._classic_algorithms
        if alg_instances is None:
            print("[WARN] Classic algorithms not properly initialized, skipping evaluation")
            return

        # OPTIMIZATION: Use pre-computed SNR values
        snr_values = self._snr_values
        
        # OPTIMIZATION: Cache array dimensions for repeated use
        num_elements = self._array_cfg_dict["num_elements"]

        # Prepare scenarios ----------------------------------------------
        scenarios = self._selected_scenarios()

        # SPEED OPTIMIZATION: Pre-allocate result containers with known structure
        res_dict: dict[str, dict[str, dict[float, float]]] = {}
        time_dict: dict[str, dict[str, list[float]]] = {}
        
        # SPEED OPTIMIZATION: Pre-allocate arrays for batch processing
        total_samples = len(self._base_dataset)
        print(f"[INFO] Processing {len(scenarios)} scenarios with {len(snr_values)} SNR values and {len(alg_instances)} algorithms")

        # Iterate scenarios ----------------------------------------------
        for scen in scenarios:
            scen_name = scen["name"]
            scen_ds = self._filter_dataset_by_scenario(scen)
            if len(scen_ds) == 0:
                print(f"  [INFO] No samples for scenario '{scen_name}', skipping.")
                continue

            res_dict[scen_name] = {}
            time_dict[scen_name] = {}

            for snr in snr_values:
                snr_ds = scen_ds.filter(snr=snr)
                if len(snr_ds) == 0:
                    continue
                
                # SPEED OPTIMIZATION: Limit samples for faster testing if requested
                original_size = len(snr_ds)
                if self.cfg.max_samples_per_snr and len(snr_ds) > self.cfg.max_samples_per_snr:
                    # Use first N samples for consistent results
                    snr_ds.indices = snr_ds.indices[:self.cfg.max_samples_per_snr]
                    print(f"  [INFO] Limited to {self.cfg.max_samples_per_snr} samples (from {original_size}) for SNR {snr} dB")

                for alg_name, alg in alg_instances.items():
                    # SPEED OPTIMIZATION: Pre-allocate arrays for results
                    dataset_size = len(snr_ds)
                    rmse_vals = []
                    timing_vals = []
                    rmse_vals.reserve(dataset_size) if hasattr(rmse_vals, 'reserve') else None
                    timing_vals.reserve(dataset_size) if hasattr(timing_vals, 'reserve') else None

                    # SPEED OPTIMIZATION: Cache algorithm type check
                    is_rootmusic = alg_name.lower() == "rootmusic"
                    
                    for idx in range(dataset_size):
                        sample = snr_ds[idx]
                        
                        # SPEED OPTIMIZATION: Streamlined source count determination
                        ns_label = sample["labels"].get("num_sources")
                        expected_sources = int(np.sum(ns_label)) if ns_label is not None else None

                        # SPEED OPTIMIZATION: More efficient DOA extraction
                        doas_raw = sample["labels"]["doas"]
                        if isinstance(doas_raw, np.ndarray):
                            all_doas = doas_raw[~np.isnan(doas_raw)].tolist()
                        else:
                            all_doas = [float(d) for d in doas_raw if not np.isnan(float(d))]
                        true_doas = all_doas[:expected_sources] if expected_sources else all_doas

                        # SPEED OPTIMIZATION: More efficient signal preparation
                        recv = sample["received_signal"].numpy()
                        if recv.ndim == 1:
                            recv = recv.reshape(num_elements, -1)
                        if recv.dtype != np.complex64 and recv.dtype != np.complex128:
                            recv = recv.astype(np.complex64)  # Use complex64 instead of complex128 for speed

                        alg.set_received_data(recv)

                        # SPEED OPTIMIZATION: Update sources only when changed
                        if expected_sources and expected_sources > 0 and getattr(alg, 'num_sources', None) != expected_sources:
                            alg.num_sources = expected_sources

                        # SPEED OPTIMIZATION: Use cached algorithm type check
                        t0 = time.time()
                        if is_rootmusic:
                            est_doas, *_ = alg.estimate_doa()
                        else:
                            est_doas, _ = alg.estimate_doa()
                        elapsed_ms = (time.time() - t0) * 1000.0
                        timing_vals.append(elapsed_ms)

                        # SPEED OPTIMIZATION: More efficient array truncation
                        if len(est_doas) > len(true_doas):
                            est_doas = est_doas[:len(true_doas)]

                        rmse = self._rmspe(est_doas, true_doas)
                        if not np.isinf(rmse):
                            rmse_vals.append(rmse)

                    # SPEED OPTIMIZATION: Use numpy operations for statistics
                    if rmse_vals:
                        mean_rmse = float(np.mean(rmse_vals))
                        res_dict[scen_name].setdefault(alg_name, {})[float(snr)] = mean_rmse  # Ensure SNR is Python float
                    else:
                        mean_rmse = float('inf')
                        
                    if timing_vals:
                        mean_timing = float(np.mean(timing_vals))
                        time_dict[scen_name].setdefault(alg_name, []).append(mean_timing)
                    else:
                        mean_timing = 0.0

                    # SPEED OPTIMIZATION: More efficient progress reporting
                    print(f"  [{scen_name}] {alg_name.upper()} | SNR {snr:+3d} dB | "
                          f"RMSE={mean_rmse:6.2f}° | {mean_timing:5.1f} ms | {len(rmse_vals):4d} samples")

        self._results["classic"] = res_dict
        self._timings["classic"] = time_dict

    def _plot_rmspe_vs_snr(self):
        """Generate RMSPE vs SNR plots for classic algorithms."""
        if not self.cfg.create_plots or "classic" not in self._results:
            return

        try:
            import matplotlib.pyplot as plt
            import seaborn as sns
            plt.style.use('default')
            sns.set_palette("husl")
        except ImportError:
            print("[WARN] Matplotlib/Seaborn not available, skipping plots")
            return

        classic_results = self._results["classic"]
        if not classic_results:
            return

        # Create plots for each scenario
        for scenario_name, alg_results in classic_results.items():
            if not alg_results:
                continue

            plt.figure(figsize=(10, 6))
            
            for alg_name, snr_rmse_dict in alg_results.items():
                if not snr_rmse_dict:
                    continue
                    
                # Sort by SNR for proper line plotting
                snr_vals = sorted(snr_rmse_dict.keys())
                rmse_vals = [snr_rmse_dict[snr] for snr in snr_vals]
                
                plt.plot(snr_vals, rmse_vals, 'o-', label=alg_name.upper(), linewidth=2, markersize=6)

            plt.xlabel('SNR (dB)', fontsize=12)
            plt.ylabel('RMSPE (degrees)', fontsize=12)
            plt.title(f'RMSPE vs SNR - {scenario_name.replace("_", " ").title()}', fontsize=14)
            plt.grid(True, alpha=0.3)
            plt.legend(fontsize=10)
            # Linear scale for RMSPE (removed log scale as requested)
            
            # Save plot
            plot_filename = f"rmspe_vs_snr_{scenario_name}.png"
            plot_path = self._results_dir / plot_filename
            plt.savefig(plot_path, dpi=300, bbox_inches='tight')
            plt.close()
            
            print(f"[INFO] Saved plot: {plot_path}")

