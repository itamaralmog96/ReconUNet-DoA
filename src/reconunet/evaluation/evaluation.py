@dataclass
class EvaluationConfig:
    """User-facing configuration for :class:`DOAEvaluator`."""

    # --- Required ---------------------------------------------------------
    dataset_path: str  # Path to ``*.h5`` dataset generated by Tri4Net

    # --- Optional knobs ----------------------------------------------------
    classic_algorithms: List[str] = field(
        default_factory=lambda: ["beamformer", "music", "mvdr", "rootmusic"]
    )
    deep_models: List[str] = field(default_factory=list)  # model registry keys
    augmented_models: List[str] = field(default_factory=list)  # registry keys

    snr_values: Optional[List[float]] = None  # If ``None`` → evaluate all
    scenarios: Optional[List[str]] = None  # If ``None`` → evaluate all

    # Mapping ``model_key -> path/to/weights.pt`` (optional)
    model_weight_paths: Dict[str, str] = field(default_factory=dict)

    results_dir: Optional[str] = None  # Defaults to ``Tri4Net/results/evaluation``
    batch_size: int = 64
    num_workers: int = 0  # Torch DataLoader workers

    # Plotting toggle (classic part always plots)
    create_plots: bool = True
    device: str = "cuda" if torch.cuda.is_available() else "cpu"

    # Misc
    tau: Optional[int] = None  # relevant for SubspaceNet-family
    
    # SPEED OPTIMIZATION: Limit samples for quick testing
    max_samples_per_snr: Optional[int] = None  # If set, limits samples per SNR for faster testing

    # --- Category toggles --------------------------------------------------
    run_classic: bool = True
    run_deep: bool = True
    run_augmented: bool = True

    # ------------------------------------------------------------------
    def __post_init__(self):
        """Normalise optional list parameters.

        Empty lists (e.g. ``scenarios=[]``) are treated the same as *not
        specified*, hence converted to ``None`` so downstream evaluators fall
        back to their default *evaluate-all* behaviour.
        """

        if self.scenarios is not None and len(self.scenarios) == 0:
            self.scenarios = None

        if self.snr_values is not None and len(self.snr_values) == 0:
            self.snr_values = None

    def resolve_paths(self, project_root: Path) -> None:
        """Resolve *results_dir* relative to *project_root* if required."""
        if self.results_dir is None:
            self.results_dir = str(project_root / "results" / "evaluation")
        Path(self.results_dir).mkdir(parents=True, exist_ok=True)


